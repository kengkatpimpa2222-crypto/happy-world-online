import { z } from 'zod';
import { BUSINESS_PRODUCT_CODES } from './game-config';

/** Header name the client must send on money-moving POSTs. */
export const IDEMPOTENCY_HEADER = 'idempotency-key';
export const idempotencyKeySchema = z
  .string()
  .regex(/^[A-Za-z0-9_-]{8,64}$/, 'Idempotency-Key must be 8-64 chars [A-Za-z0-9_-]');

export const ageBandSchema = z.enum(['UNDER_13', 'TEEN_13_17', 'ADULT_18_PLUS']);
export const localeSchema = z.enum(['th', 'en', 'zh']);
export const currencySchema = z.enum(['GOLD', 'GEMS']);

// ---- Auth ----
export const guestAuthSchema = z
  .object({
    /** Random per-install id generated by the client; used only for abuse detection. */
    deviceId: z.string().min(8).max(128),
    ageBand: ageBandSchema,
    locale: localeSchema.default('th'),
  })
  .strict();
export type GuestAuthRequest = z.infer<typeof guestAuthSchema>;

const passwordSchema = z.string().min(8).max(128);
export const linkAccountSchema = z
  .object({ email: z.email().max(254), password: passwordSchema })
  .strict();
export type LinkAccountRequest = z.infer<typeof linkAccountSchema>;

export const loginSchema = z.object({ email: z.email().max(254), password: z.string().min(1).max(128) }).strict();
export type LoginRequest = z.infer<typeof loginSchema>;

export const refreshSchema = z.object({ refreshToken: z.string().min(20).max(200) }).strict();
export type RefreshRequest = z.infer<typeof refreshSchema>;

// ---- Player ----
/** Thai/Latin letters, digits, space, underscore. No @ . / so URLs and e-mails can't be typed. */
export const DISPLAY_NAME_PATTERN = /^[A-Za-z0-9฀-๿ _]+$/;
export const displayNameSchema = z
  .string()
  .trim()
  .min(2)
  .max(16)
  .regex(DISPLAY_NAME_PATTERN, 'Only Thai/English letters, digits, space and _')
  // 5+ digits in a row look like phone numbers / IDs: block to protect personal info
  .refine((s) => !/\d{5,}/.test(s), 'Display name must not contain long numbers');

export const avatarSchema = z
  .object({
    bodyColor: z.string().regex(/^#[0-9A-Fa-f]{6}$/).optional(),
    outfitItemId: z.string().max(64).nullable().optional(),
    hairItemId: z.string().max(64).nullable().optional(),
    accessoryItemId: z.string().max(64).nullable().optional(),
  })
  .strict();
export type Avatar = z.infer<typeof avatarSchema>;

export const updateProfileSchema = z
  .object({
    displayName: displayNameSchema.optional(),
    avatar: avatarSchema.optional(),
    locale: localeSchema.optional(),
  })
  .strict()
  .refine((v) => Object.keys(v).length > 0, 'At least one field is required');
export type UpdateProfileRequest = z.infer<typeof updateProfileSchema>;

// ---- Store ----
export const storePurchaseSchema = z
  .object({
    itemId: z.string().min(1).max(64),
    quantity: z.number().int().min(1).max(10).default(1),
    currency: currencySchema,
  })
  .strict();
export type StorePurchaseRequest = z.infer<typeof storePurchaseSchema>;

export const verifyPurchaseSchema = z
  .object({
    provider: z.enum(['GOOGLE_PLAY', 'DEV_MOCK']),
    productId: z.string().min(1).max(100),
    purchaseToken: z.string().min(10).max(4096),
  })
  .strict();
export type VerifyPurchaseRequest = z.infer<typeof verifyPurchaseSchema>;

// ---- Business ----
export const businessProductCodeSchema = z.enum(BUSINESS_PRODUCT_CODES as [string, ...string[]]);

export const restockSchema = z
  .object({ productCode: businessProductCodeSchema, quantity: z.number().int().min(1).max(100) })
  .strict();
export type RestockRequest = z.infer<typeof restockSchema>;

export const setPriceSchema = z
  .object({ productCode: businessProductCodeSchema, price: z.number().int().min(1).max(10000) })
  .strict();
export type SetPriceRequest = z.infer<typeof setPriceSchema>;

export const upgradeBusinessSchema = z
  .object({
    /** Level the client believes the shop is at; protects against double-tap upgrades. */
    expectedLevel: z.number().int().min(1).max(10),
  })
  .strict();
export type UpgradeBusinessRequest = z.infer<typeof upgradeBusinessSchema>;

// ---- Living shop (Phase 5) ----
/** Same character rules as display names; shown to other players in the market. */
export const shopNameSchema = z
  .string()
  .trim()
  .min(2)
  .max(20)
  .regex(DISPLAY_NAME_PATTERN, 'Only Thai/English letters, digits, space and _')
  .refine((s) => !/\d{5,}/.test(s), 'Shop name must not contain long numbers');

export const renameBusinessSchema = z.object({ name: shopNameSchema }).strict();
export type RenameBusinessRequest = z.infer<typeof renameBusinessSchema>;

export const setShelfSchema = z
  .object({
    productCode: businessProductCodeSchema,
    /** Units that should be on the stall after the call (0 = take the product off the stall). */
    quantity: z.number().int().min(0).max(200),
  })
  .strict();
export type SetShelfRequest = z.infer<typeof setShelfSchema>;

export const shopStatusSchema = z.enum(['OPEN', 'PAUSED', 'CLOSED']);
export const setShopStatusSchema = z.object({ status: shopStatusSchema }).strict();
export type SetShopStatusRequest = z.infer<typeof setShopStatusSchema>;

export const ackShopReportSchema = z
  .object({
    /** `until` of the report the player saw; later sales stay in the next report. Defaults to now. */
    until: z.iso.datetime().optional(),
  })
  .strict();
export type AckShopReportRequest = z.infer<typeof ackShopReportSchema>;

export const uuidParamSchema = z.uuid();
export const questIdParamSchema = z.string().regex(/^[a-z0-9_]{2,64}$/);
